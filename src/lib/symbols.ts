/** Characters with no meaning on their own (control codes, soft hyphens, replacement marks): dropped rather than shown as a box. */
function invisible(code: number): boolean {
  return (
    (code < 0x20 && code !== 0x09 && code !== 0x0a && code !== 0x0d) ||
    code === 0x7f ||
    code === 0xad ||
    code === 0x200b ||
    code === 0xfeff ||
    code === 0xfffd
  )
}

export function fixSymbols(text: string): string {
  let out = ''
  for (const char of text) {
    const code = char.codePointAt(0) ?? 0
    if (code >= 0x80 && code <= 0x9f) out += WINDOWS_1252[code] ?? ''
    else if (code >= 0xf020 && code <= 0xf0ff) out += SYMBOL_FONT[code - 0xf000] ?? (code >= 0xf030 && code <= 0xf039 ? String(code - 0xf030) : '')
    else if (!invisible(code)) out += char
  }
  return out
}
